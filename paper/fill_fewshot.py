"""Write paper/fewshot.tex from a finished few-shot baseline run (B0-FS).

Usage (repo root, after ``bash scripts/run_fewshot_b0.sh`` and downloading its folder)::

    python -P paper/fill_fewshot.py results/<date>-b0-fewshot

Without a run, ``paper/fewshot.tex`` keeps its placeholder values and the paper
prints the B0-FS row as "pending".
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    run = Path(sys.argv[1])
    rows = [
        json.loads(line)
        for line in (run / "episodes.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    if len(rows) != 300:
        raise SystemExit(f"expected 300 holdout episodes, found {len(rows)}")
    done = [row for row in rows if row["status"] == "completed"]

    def metric(row: dict, name: str) -> float:
        return float(row["metrics"][name])

    em_all = 100 * sum(metric(r, "answer_exact_match") for r in done) / len(rows)
    em_done = 100 * sum(metric(r, "answer_exact_match") for r in done) / max(len(done), 1)
    grounded = sum(
        metric(r, "answer_exact_match") == 1.0
        and bool(r["citations"])
        and metric(r, "citation_precision") == 1.0
        for r in done
    )
    pgem = 100 * grounded / len(rows)
    precision = sum(metric(r, "citation_precision") for r in done) / max(len(done), 1)
    coverage = sum(metric(r, "evidence_coverage") for r in done) / max(len(done), 1)

    lines = [
        "% Generated by paper/fill_fewshot.py from " + run.as_posix(),
        r"\newcommand{\FSpending}{0}",
        rf"\newcommand{{\FSem}}{{{em_all:.1f}}}",
        rf"\newcommand{{\FSemdone}}{{{em_done:.1f}}}",
        rf"\newcommand{{\FSpgem}}{{{pgem:.1f}}}",
        rf"\newcommand{{\FSprec}}{{{precision:.3f}}}",
        rf"\newcommand{{\FScov}}{{{coverage:.3f}}}",
        rf"\newcommand{{\FSdone}}{{{len(done)}}}",
    ]
    (ROOT / "paper" / "fewshot.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
